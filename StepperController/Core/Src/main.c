/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the System Power */
  SystemPower_Config();

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ICACHE_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED_GREEN);
  BSP_LED_Init(LED_BLUE);
  BSP_LED_Init(LED_RED);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* USER CODE BEGIN BSP */

  /* -- Sample board code to send message over COM1 port ---- */
  printf("Welcome to STM32 world !\n\r");

  /* -- Sample board code to switch on leds ---- */
  BSP_LED_On(LED_GREEN);
  BSP_LED_On(LED_BLUE);
  BSP_LED_On(LED_RED);

  //!adam
  // Reset ENA (LOW is turned on)
  HAL_GPIO_WritePin(ENA_GPIO_PORT, ENA_PIN, GPIO_PIN_RESET);
  // Set DIR (unknown direction on SET)
  HAL_GPIO_WritePin(DIR_GPIO_PORT, DIR_PIN, GPIO_PIN_SET);
  HAL_Delay(1);
  // Start pulses
  __HAL_DBGMCU_FREEZE_TIM1();
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_Base_Start_IT(&htim1);
  /* USER CODE END BSP */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* -- Sample board code for User push-button in interrupt mode ---- */
    if (BspButtonState == BUTTON_PRESSED)
    {
      /* Update button state */
      BspButtonState = BUTTON_RELEASED;
      // button went down - short press or hold is decided later
      if (!buttonHeld)
      {
        buttonHeld = 1;
        holdHandled = 0;
        pressStart = HAL_GetTick();
      }
    }

    if (buttonHeld)
    {
      uint32_t heldFor = HAL_GetTick() - pressStart;

      if (BSP_PB_GetState(BUTTON_USER) == GPIO_PIN_SET)
      {
        // still held: after HOLD_TIME_MS stop/start the motor (once per press)
        if (!holdHandled && heldFor >= HOLD_TIME_MS)
        {
          holdHandled = 1;
          if (motorRunning)
          {
            HAL_TIM_PWM_Stop(&htim1, TIM_CHANNEL_1);
            motorRunning = 0;
          }
          else
          {
            HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
            motorRunning = 1;
          }
        }
      }
      else
      {
        // released: if it wasn't a hold (or a bounce), it was a short press
        buttonHeld = 0;
        if (!holdHandled && heldFor >= DEBOUNCE_TIME_MS)
        {
          /* -- Sample board code to toggle lecds ---- */
          BSP_LED_Toggle(LED_GREEN);
          BSP_LED_Toggle(LED_BLUE);
          BSP_LED_Toggle(LED_RED);

          /* ..... Perform your action ..... */
          if (motorRunning)
          {
            //stop pules
            HAL_TIM_PWM_Stop(&htim1, TIM_CHANNEL_1);
            // change direction
            HAL_GPIO_TogglePin(DIR_GPIO_PORT, DIR_PIN);
            HAL_Delay(1);
            //start again
            HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
          }
          else
          {
            // stopped: only change direction, the next start uses it
            HAL_GPIO_TogglePin(DIR_GPIO_PORT, DIR_PIN);
          }
        }
      }
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

